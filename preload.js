const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("desktopBridge", {
  openChromeProfile: (accountId, channel, monitor = false) => ipcRenderer.invoke("open-chrome-profile", { accountId, channel, monitor }),
  openAuthInProfile: (accountId, url) => ipcRenderer.invoke("open-auth-in-profile", { accountId, url }),
  openBetterTtvInProfile: (accountId) => ipcRenderer.invoke("open-betterttv-in-profile", { accountId }),
  installPointsMonitor: (accountId, channel) => ipcRenderer.invoke("install-points-monitor", { accountId, channel }),
  openExternal: (url) => ipcRenderer.invoke("open-external", url),
  selectArcadeFolder: () => ipcRenderer.invoke("select-arcade-folder"),
  openArcadeWindow: () => ipcRenderer.invoke("open-arcade-window"),
  launchArcadeGame: (folder) => ipcRenderer.invoke("launch-arcade-game", folder),
  checkForUpdates: () => ipcRenderer.invoke("check-for-updates"),
  downloadUpdate: () => ipcRenderer.invoke("download-update"),
  installUpdate: () => ipcRenderer.invoke("install-update"),
  onUpdateStatus: (callback) => ipcRenderer.on("update-status", (_event, data) => callback(data)),
  startTwitchAuth: (accountId, clientId, redirectUri) => ipcRenderer.invoke("start-twitch-auth", { accountId, clientId, redirectUri }),
  onTwitchAuthComplete: (callback) => ipcRenderer.on("twitch-auth-complete", (_event, data) => callback(data)),
  joinIrc: (accountId, channel) => ipcRenderer.invoke("irc-join", { accountId, channel }),
  partIrc: (accountId) => ipcRenderer.invoke("irc-part", { accountId }),
  sendIrcMessage: (accountId, message) => ipcRenderer.invoke("irc-send-message", { accountId, message }),
  onIrcStatus: (callback) => ipcRenderer.on("irc-status", (_event, data) => callback(data)),
  onIrcEvent: (callback) => ipcRenderer.on("irc-event", (_event, data) => callback(data)),
  onPointsUpdate: (callback) => ipcRenderer.on("points-update", (_event, data) => callback(data)),
  getChannelProfile: (accountId, channel) => ipcRenderer.invoke("get-channel-profile", { accountId, channel }),
  setTrayMode: (enabled) => ipcRenderer.invoke("set-tray-mode", enabled),
  setHardwareAcceleration: (enabled) => ipcRenderer.invoke("set-hardware-acceleration", enabled),
  createBackup: (cache) => ipcRenderer.invoke("create-backup", cache),
  restoreBackup: () => ipcRenderer.invoke("restore-backup"),
  quitForRestore: () => ipcRenderer.invoke("quit-for-restore"),
  loadAccountCache: () => ipcRenderer.invoke("load-account-cache"),
  saveAccountCache: (accounts) => ipcRenderer.invoke("save-account-cache", accounts),
  recoverAuthorizedAccounts: () => ipcRenderer.invoke("recover-authorized-accounts"),
});
